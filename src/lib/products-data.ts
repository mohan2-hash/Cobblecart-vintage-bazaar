export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id || p.slug === id);
}

export function getCheapestStore(product: Product) {
  const available = product.storePrices.filter((s) => s.inStock);
  if (available.length === 0) return product.storePrices[0];
  return available.reduce((min, curr) => (curr.price < min.price ? curr : min), available[0]);
}

export function calculateMaxSavings(product: Product) {
  const inStockPrices = product.storePrices.filter((s) => s.inStock).map((s) => s.price);
  if (inStockPrices.length <= 1) return 0;
  const highest = Math.max(...inStockPrices);
  const lowest = Math.min(...inStockPrices);
  return highest - lowest;
}
